// Bundles the TypeScript standard library type files (ES2020) that the in-app type checker needs.
import { readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('../node_modules/typescript/lib/', import.meta.url);
const seen = new Map();
const walk = (n) => {
  if (seen.has(n)) return;
  const t = readFileSync(new URL(`lib.${n}.d.ts`, dir), 'utf8');
  seen.set(n, t);
  for (const m of t.matchAll(/<reference lib="([^"]+)"/g)) walk(m[1]);
};
walk('es2020');
const out = Object.fromEntries(
  [...seen].map(([n, t]) => [`lib.${n}.d.ts`, t.replace(/\/\*![\s\S]*?\*\//, '')]),
);
writeFileSync(
  new URL('../src/runtime/tslib.js', import.meta.url),
  `// generated by scripts/gen-tslib.mjs from typescript/lib (Apache-2.0)\nexport const LIBS = ${JSON.stringify(out)};\n`,
);
console.log(seen.size, 'lib files');
