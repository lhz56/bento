const has = (re) => (c) => {
  const hit = c.all.match(re);
  return hit ? hit[0].slice(0, 60) : null;
};
const hdr = (k, re) => (c) =>
  c.headers[k] && (!re || re.test(c.headers[k])) ? `${k}: ${c.headers[k].slice(0, 40)}` : null;

const S = (id, name, slug, cat, test, what, when, alt = []) => ({
  id,
  name,
  slug,
  cat,
  test,
  what,
  when,
  alt,
});
