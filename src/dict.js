export function lookup(word, lang) {
  if (lang === 'typescript' && Object.prototype.hasOwnProperty.call(TS, word))
    return { title: word, ...TS[word] };
  const d = lang === 'python' ? PY : JS;
  if (Object.prototype.hasOwnProperty.call(d, word)) return { title: word, ...d[word] };
  return null;
}
